CREATE TABLE IF NOT EXISTS `faccao_personagem` (
  `guid` INT UNSIGNED NOT NULL,
  `equipe` TINYINT UNSIGNED NOT NULL,
  `aplicar_no_login` TINYINT UNSIGNED NOT NULL DEFAULT 0,
  `alterado_em` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`guid`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
